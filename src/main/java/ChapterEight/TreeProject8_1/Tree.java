package ChapterEight.TreeProject8_1;

import java.util.Stack;

// Класс Tree представляет целое двоичное дерево.
public class Tree {

    // Поле root хранит ссылку на корень дерева.
    // private означает, что напрямую работать с этим полем
    // можно только внутри класса Tree.
    private Node root;

    // Конструктор класса Tree.
    // Он вызывается при выполнении new Tree().
    public Tree(){

        // Новое дерево изначально является пустым,
        // поэтому ссылка на его корень равна null.
        root = null;
    }

    // Метод получает массив отдельных листовых узлов
    // и строит из них одно двоичное дерево.
    public void treeByRow(Node[] nodeArr){

        // Создаём массив объектов Tree.
        // Каждый введённый узел сначала будет корнем
        // отдельного одноузлового дерева.
        // Такой набор отдельных деревьев называется лесом.
        Tree[] forest = new Tree[nodeArr.length];

        // Счётчик узлов массива nodeArr.
        // Показывает, какой узел сейчас превращается
        // в отдельное дерево.
        int nodeCounter = 0;

        // Количество деревьев, которые сейчас считаются активными.
        // В начале их столько же, сколько исходных узлов.
        int numberOfActiveTrees = nodeArr.length;

        // Запускаем цикл создания одноузловых деревьев.
        // Само условие true означает бесконечный цикл,
        // поэтому выход будет выполнен вручную через break.
        while(true){

            // Если счётчик достиг длины массива,
            // значит, все узлы уже обработаны.
            if(nodeCounter == nodeArr.length){

                // Прерываем цикл while.
                break;
            }

            // Создаём отдельное пустое дерево
            // для текущего узла массива nodeArr.
            Tree tree = new Tree();

            // Текущий узел становится корнем созданного дерева.
            // Например, при nodeCounter = 0 корнем будет nodeArr[0].
            tree.root = nodeArr[nodeCounter];

            // Сохраняем созданное одноузловое дерево
            // в соответствующей позиции массива forest.
            forest[nodeCounter] = tree;

            // Переходим к следующему узлу массива nodeArr.
            nodeCounter = nodeCounter + 1;
        }

        // Продолжаем объединять деревья,
        // пока в лесу существует более одного активного дерева.
        while(numberOfActiveTrees > 1){

            // Индекс, куда будет записано
            // следующее объединённое дерево.
            // В начале каждого раунда запись начинается с позиции 0.
            int writeIndex = 0; //Куда записываем

            // Индекс дерева, которое следующим
            // будет прочитано из активной части леса.
            int treeCounter = 0; //Откуда чиатем

            // Цикл работает, пока в активной части леса
            // остаётся минимум два дерева.
            //
            // Например, если активны 5 деревьев,
            // условие допускает treeCounter = 0 и 2:
            // берутся пары 0–1 и 2–3.
            while (treeCounter <= numberOfActiveTrees - 2){

                // Создаём новое временное дерево,
                // которое объединит два дерева текущей пары.
                Tree temp = new Tree();

                // Создаём новый родительский узел.
                Node node = new Node();

                // Во внутренний родительский узел записываем +.
                // Буквы будут находиться только в листовых узлах.
                node.sData = "+";

                // Новый узел + становится корнем
                // временного объединённого дерева.
                temp.root = node;

                // Корень первого дерева пары
                // становится левым потомком нового узла +.
                //
                // Сначала используется текущее значение treeCounter,
                // а после обращения к массиву оно увеличивается.
                temp.root.leftChild = forest[treeCounter++].root;

                // Корень второго дерева пары
                // становится правым потомком нового узла +.
                //
                // После этой строки treeCounter будет увеличен
                // ещё на единицу, то есть всего на 2 за пару.
                temp.root.rightChild = forest[treeCounter++].root;

                // Записываем объединённое дерево
                // в начало массива forest.
                //
                // После записи writeIndex увеличивается,
                // чтобы следующий результат попал
                // в следующую свободную позицию.
                forest[writeIndex++] = temp;
            }

            // Проверяем, осталось ли одно дерево без пары.
            //
            // Это происходит, когда количество активных деревьев нечётное.
            if(treeCounter < numberOfActiveTrees){

                // Переносим последнее непарное дерево
                // в новый активный набор без изменений.
                forest[writeIndex] = forest[treeCounter];

                // Увеличиваем индекс записи,
                // потому что перенесённое дерево тоже является
                // частью нового активного набора.
                writeIndex++;
            }

            // После раунда writeIndex равен количеству деревьев,
            // созданных или перенесённых в новый активный набор.
            //
            // Это количество будет использоваться
            // в следующем раунде объединения.
            numberOfActiveTrees = writeIndex;
        }

        // Когда numberOfActiveTrees стал равен 1,
        // в forest[0] находится единственное итоговое дерево.
        //
        // Сохраняем его корень в поле root текущего объекта Tree.
        root = forest[0].root;
    }

    // Метод выбирает один из трёх видов обхода дерева.
    // Значение traverseType определяет нужный обход.
    public void traverse(int traverseType) {

        // switch проверяет значение traverseType.
        switch (traverseType) {

            // Если передано значение 1,
            // выполняется прямой обход.
            case 1:

                // Выводим название обхода.
                System.out.print("\nPreorder traversal: ");

                // Запускаем прямой обход от корня.
                preOrder(root);

                // Завершаем выполнение switch.
                break;

            // Если передано значение 2,
            // выполняется симметричный обход.
            case 2:

                // Выводим название обхода.
                System.out.print("\nInorder traversal: ");

                // Запускаем симметричный обход от корня.
                inOrder(root);

                // Завершаем выполнение switch.
                break;

            // Если передано значение 3,
            // выполняется обратный обход.
            case 3:

                // Выводим название обхода.
                System.out.print("\nPostorder traversal: ");

                // Запускаем обратный обход от корня.
                postOrder(root);

                // Завершаем выполнение switch.
                break;

            // Сюда программа попадёт,
            // если передано любое другое число.
            default:

                // Сообщаем, что тип обхода неизвестен.
                System.out.print("\nUnknown traversal type");
        }

        // После обхода переходим на новую строку.
        System.out.println();
    }

    // Метод выполняет прямой обход:
    // текущий узел → левое поддерево → правое поддерево.
    private void preOrder(Node node) {

        // Если текущего узла нет,
        // текущая ветвь рекурсии закончилась.
        if (node == null) {

            // Возвращаемся к предыдущему вызову метода.
            return;
        }

        // Сначала выводим содержимое текущего узла.
        System.out.print(node.sData + " ");

        // После текущего узла обходим левое поддерево.
        preOrder(node.leftChild);

        // После левого поддерева обходим правое.
        preOrder(node.rightChild);
    }

    // Метод выполняет симметричный обход:
    // левое поддерево → текущий узел → правое поддерево.
    private void inOrder(Node node) {

        // Если текущего узла нет,
        // текущая ветвь обхода закончилась.
        if (node == null) {

            // Возвращаемся к предыдущему рекурсивному вызову.
            return;
        }

        // Сначала полностью обходим левое поддерево.
        inOrder(node.leftChild);

        // Затем выводим текущий узел.
        System.out.print(node.sData + " ");

        // После текущего узла обходим правое поддерево.
        inOrder(node.rightChild);
    }

    // Метод выполняет обратный обход:
    // левое поддерево → правое поддерево → текущий узел.
    private void postOrder(Node node) {

        // Если текущего узла нет,
        // текущая ветвь рекурсии закончилась.
        if (node == null) {

            // Возвращаемся к предыдущему вызову.
            return;
        }

        // Сначала обходим левое поддерево.
        postOrder(node.leftChild);

        // Затем обходим правое поддерево.
        postOrder(node.rightChild);

        // Текущий узел выводится последним.
        System.out.print(node.sData + " ");
    }

    // Метод выводит двоичное дерево по уровням.
    // Для этого используются два стека:
    // globalStack — текущий уровень;
    // localStack — следующий уровень.
    public void displayTree() {

        // Создаём стек текущего уровня.
        // Здесь используется Stack без указанного типа,
        // поэтому при извлечении понадобится преобразование к Node.
        Stack globalStack = new Stack();

        // Помещаем корневой узел в стек.
        // С него начнётся вывод дерева.
        globalStack.push(root);

        // Начальное количество пробелов перед корнем.
        // После каждого уровня это значение будет уменьшаться вдвое.
        int nBlanks = 32;

        // Флаг завершения вывода.
        // false означает, что строки дерева ещё нужно обрабатывать.
        boolean isRowEmpty = false;

        // Выводим верхнюю границу дерева.
        System.out.println(
                "......................................................");

        // Продолжаем вывод, пока существуют уровни
        // с настоящими, ненулевыми узлами.
        while(isRowEmpty==false) {

            // Создаём стек, в который будут помещаться
            // потомки узлов текущего уровня.
            Stack localStack = new Stack();

            // Предполагаем, что следующая строка будет пустой.
            // Если у какого-нибудь узла найдутся потомки,
            // значение снова будет изменено на false.
            isRowEmpty = true;

            // Выводим начальный отступ перед первым узлом уровня.
            for(int j=0; j<nBlanks; j++)

                // На каждой итерации выводится один пробел.
                System.out.print(' ');

            // Обрабатываем все узлы текущего уровня,
            // пока globalStack не станет пустым.
            while(globalStack.isEmpty()==false) {

                // Извлекаем верхний объект из globalStack
                // и преобразуем его к типу Node.
                Node temp = (Node)globalStack.pop();

                // Проверяем, существует ли узел.
                if(temp != null) {

                    // Выводим данные существующего узла.
                    System.out.print(temp.sData);

                    // Помещаем левого потомка
                    // в стек следующего уровня.
                    // Если потомка нет, в стек попадёт null.
                    localStack.push(temp.leftChild);

                    // Помещаем правого потомка
                    // в стек следующего уровня.
                    localStack.push(temp.rightChild);

                    // Проверяем, есть ли у текущего узла
                    // хотя бы один настоящий потомок.
                    if(temp.leftChild != null ||
                            temp.rightChild != null)

                        // Если потомок существует,
                        // следующая строка не является пустой,
                        // поэтому цикл должен продолжиться.
                        isRowEmpty = false;
                }

                // Этот блок выполняется,
                // если вместо узла из стека был извлечён null.
                else
                {
                    // Выводим обозначение отсутствующего узла.
                    System.out.print("--");

                    // Сохраняем пустую позицию
                    // для левого потомка отсутствующего узла.
                    localStack.push(null);

                    // Сохраняем пустую позицию
                    // для правого потомка отсутствующего узла.
                    localStack.push(null);
                }

                // Выводим расстояние между текущим узлом
                // и следующим узлом этого же уровня.
                for(int j=0; j<nBlanks*2-2; j++)

                    // Выводим один пробел за одну итерацию.
                    System.out.print(' ');
            }

            // После завершения текущего уровня
            // переходим на новую строку.
            System.out.println();

            // Для следующего уровня уменьшаем
            // количество начальных пробелов в два раза.
            nBlanks /= 2;

            // Перекладываем узлы следующего уровня
            // из localStack обратно в globalStack.
            //
            // При перекладывании порядок переворачивается,
            // поэтому левый потомок будет извлечён
            // раньше правого потомка.
            while(localStack.isEmpty()==false)

                // Извлекаем верхний элемент localStack
                // и помещаем его в globalStack.
                globalStack.push(localStack.pop());
        }

        // После завершения вывода всех уровней
        // печатаем нижнюю границу дерева.
        System.out.println(
                "......................................................");
    }
}
